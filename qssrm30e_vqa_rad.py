def train_qssrm(

    model,

    train_loader,

    val_loader,

    optimizer,

    scheduler,

    epochs,

    accumulation_steps,

    patience,

    save_path

):


    global best_accuracy
    global history



    patience_counter = 0



    for epoch in range(epochs):


        print("\n" + "="*60)

        print(
            f"Epoch {epoch+1}/{epochs}"
        )

        print("="*60)



        # ==================================================
        # Train
        # ==================================================

        train_metrics = train_one_epoch(

            model=model,

            dataloader=train_loader,

            optimizer=optimizer,

            scaler=scaler,

            device=DEVICE,

            accumulation_steps=accumulation_steps

        )



        # ==================================================
        # Validation
        # ==================================================

        val_metrics = validate(

            model=model,

            dataloader=val_loader,

            device=DEVICE

        )



        train_loss = train_metrics["loss"]

        train_acc = train_metrics["accuracy"]


        val_acc = val_metrics[
            "overall_accuracy"
        ]



        # ==================================================
        # History
        # ==================================================

        history["train_loss"].append(
            train_loss
        )


        history["train_accuracy"].append(
            train_acc
        )


        history["val_loss"].append(
            val_metrics["val_loss"]
        )


        history["val_accuracy"].append(
            val_acc
        )


        history["yes_no_accuracy"].append(
            val_metrics["yes_no_accuracy"]
        )


        history["open_accuracy"].append(
            val_metrics["open_ended_accuracy"]
        )


        history["question_type_accuracy"].append(
            val_metrics["question_type_accuracy"]
        )


        history["learning_rate"].append(
            optimizer.param_groups[0]["lr"]
        )



        # ==================================================
        # Reporting
        # ==================================================

        print()


        print(
            f"Train Loss           : {train_loss:.4f}"
        )


        print(
            f"Train Accuracy       : {train_acc*100:.2f}%"
        )


        print(
            f"Validation Loss      : {val_metrics['val_loss']:.4f}"
        )


        print(
            f"Overall Accuracy     : {val_acc*100:.2f}%"
        )


        print(
            f"Yes/No Accuracy      : "
            f"{val_metrics['yes_no_accuracy']*100:.2f}%"
        )


        print(
            f"Open-ended Accuracy  : "
            f"{val_metrics['open_ended_accuracy']*100:.2f}%"
        )


        print(
            f"Question Type Acc    : "
            f"{val_metrics['question_type_accuracy']*100:.2f}%"
        )



        # ==================================================
        # Save Best
        # ==================================================

        if val_acc > best_accuracy:


            best_accuracy = val_acc

            patience_counter = 0



            checkpoint = {


                "epoch":
                    epoch + 1,


                "model_state":
                    model.state_dict(),


                "optimizer_state":
                    optimizer.state_dict(),


                "scheduler_state":
                    scheduler.state_dict(),


                "scaler_state":
                    scaler.state_dict(),


                "best_accuracy":
                    best_accuracy,


                "history":
                    history

            }



            torch.save(

                checkpoint,

                save_path

            )


            print()

            print(
                "✓ Best Two-Stage checkpoint saved"
            )



        else:


            patience_counter += 1


            print()

            print(
                f"No improvement "
                f"{patience_counter}/{patience}"
            )



        # ==================================================
        # Scheduler Step
        # ==================================================

        scheduler.step()



        # ==================================================
        # Early Stopping
        # ==================================================

        if patience_counter >= patience:


            print()

            print(
                "✓ Early stopping triggered"
            )

            break





    print("\n" + "="*60)

    print(
        "QSSRM Two-Stage Training Finished"
    )


    print(

        f"Best Accuracy: "
        f"{best_accuracy*100:.2f}%"

    )

    print("="*60)







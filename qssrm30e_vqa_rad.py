# ==========================================================
# Build Answer Vocabulary
# ==========================================================

def build_answer_vocab(
    dataset,
    min_frequency=2
):

    counter = Counter()


    for sample in dataset:

        answer = (
            str(sample["answer"])
            .lower()
            .strip()
        )

        counter[answer] += 1



    valid_answers = [

        ans

        for ans, freq in counter.items()

        if freq >= min_frequency

    ]



    answer_to_label = {

        ans: idx

        for idx, ans in enumerate(
            sorted(valid_answers)
        )

    }



    label_to_answer = {

        idx: ans

        for ans, idx in answer_to_label.items()

    }


    return answer_to_label, label_to_answer





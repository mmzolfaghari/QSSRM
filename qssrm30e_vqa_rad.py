import torch
import torch.nn as nn



class VisionEncoder(nn.Module):

    def __init__(
        self,
        clip_model,
        output_dim=512,
        train_last_blocks=2,
        dropout=0.2
    ):

        super().__init__()


        self.visual = clip_model.visual


        if not hasattr(self.visual, "trunk"):

            raise RuntimeError(
                "BiomedCLIP visual encoder has no timm trunk"
            )


        self.trunk = self.visual.trunk



        # --------------------------------------------------
        # Detect Vision Dimension
        # --------------------------------------------------

        if hasattr(self.trunk, "num_features"):

            input_dim = self.trunk.num_features


        elif hasattr(self.trunk, "embed_dim"):

            input_dim = self.trunk.embed_dim


        else:

            raise RuntimeError(
                "Cannot detect BiomedCLIP feature dimension"
            )



        # --------------------------------------------------
        # Projection
        # --------------------------------------------------

        self.projection = nn.Linear(

            input_dim,

            output_dim

        )


        self.dropout = nn.Dropout(
            dropout
        )



        # --------------------------------------------------
        # Freeze Backbone
        # --------------------------------------------------

        for p in self.trunk.parameters():

            p.requires_grad = False



        # --------------------------------------------------
        # Unfreeze Last Transformer Blocks
        # --------------------------------------------------

        if hasattr(self.trunk, "blocks"):


            total_blocks = len(
                self.trunk.blocks
            )


            start = max(
                0,
                total_blocks - train_last_blocks
            )


            for block in self.trunk.blocks[start:]:

                for p in block.parameters():

                    p.requires_grad = True



        # --------------------------------------------------
        # Train Final Norm
        # --------------------------------------------------

        if hasattr(self.trunk, "norm"):

            for p in self.trunk.norm.parameters():

                p.requires_grad = True



        # Projection trainable

        for p in self.projection.parameters():

            p.requires_grad = True




    def forward(self, images):


        x = self.trunk.forward_features(
            images
        )


        # timm newer versions

        if isinstance(x, dict):

            x = x["x"]



        if x.ndim != 3:

            raise RuntimeError(

                f"Unexpected BiomedCLIP output: {x.shape}"

            )



        # --------------------------------------------------
        # CLS + Patch Tokens
        # --------------------------------------------------

        if x.shape[1] > 1:

            cls_feature = x[:,0]

            patch_features = x[:,1:]


        else:

            cls_feature = x.mean(
                dim=1
            )

            patch_features = x



        # --------------------------------------------------
        # Projection
        # --------------------------------------------------

        global_feature = self.projection(
            cls_feature
        )


        patch_features = self.projection(
            patch_features
        )



        global_feature = self.dropout(
            global_feature
        )


        patch_features = self.dropout(
            patch_features
        )



        return (
            global_feature,
            patch_features
        )





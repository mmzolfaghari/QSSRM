import torch
import torch.nn as nn
from transformers import AutoModel



class TextEncoder(nn.Module):

    def __init__(
        self,
        model_name="microsoft/BiomedNLP-PubMedBERT-base-uncased-abstract-fulltext",
        output_dim=512,
        train_last_layers=1,
        dropout=0.2
    ):

        super().__init__()


        # --------------------------------------------------
        # PubMedBERT Backbone
        # --------------------------------------------------

        self.encoder = AutoModel.from_pretrained(
            model_name
        )


        self.hidden_dim = (
            self.encoder.config.hidden_size
        )


        self.output_dim = output_dim



        self.dropout = nn.Dropout(
            dropout
        )



        # --------------------------------------------------
        # Projection to QSSRM Shared Space
        # --------------------------------------------------

        self.projection = nn.Sequential(

            nn.Linear(
                self.hidden_dim,
                output_dim
            ),

            nn.GELU(),

            nn.LayerNorm(
                output_dim
            ),

            nn.Dropout(dropout)

        )



        # --------------------------------------------------
        # Freeze Backbone
        # --------------------------------------------------

        for param in self.encoder.parameters():

            param.requires_grad = False



        # --------------------------------------------------
        # Partial Fine-tuning
        # --------------------------------------------------

        total_layers = len(
            self.encoder.encoder.layer
        )


        for layer in self.encoder.encoder.layer[
            total_layers-train_last_layers:
        ]:

            for param in layer.parameters():

                param.requires_grad = True



    def forward(
        self,
        input_ids,
        attention_mask
    ):


        outputs = self.encoder(

            input_ids=input_ids,

            attention_mask=attention_mask,

            return_dict=True

        )



        token_features = (
            outputs.last_hidden_state
        )
        # [B,L,768]



        # --------------------------------------------------
        # Masked Mean Pooling
        # --------------------------------------------------

        mask = (
            attention_mask
            .unsqueeze(-1)
            .float()
        )


        global_feature = (

            token_features * mask

        ).sum(dim=1)


        global_feature /= (

            mask.sum(dim=1)
            .clamp(min=1e-9)

        )
        # [B,768]



        # --------------------------------------------------
        # Project to Shared 512 Space
        # --------------------------------------------------

        global_feature = self.projection(
            global_feature
        )
        # [B,512]



        token_features = self.projection(
            token_features
        )
        # [B,L,512]



        global_feature = self.dropout(
            global_feature
        )


        token_features = self.dropout(
            token_features
        )



        return (
            global_feature,
            token_features
        )






    outputs = qssrm_model(

        image,

        input_ids,

        attention_mask

    )



    fused_features = outputs[
        "fused_features"
    ]



    # prediction score

    type_pred = torch.argmax(
        outputs["question_type_logits"],
        dim=-1
    )



    if type_pred.item()==TYPE_YES_NO:


        score = torch.max(
            outputs["yes_no_logits"]
        )


    else:

        score = torch.max(
            outputs["open_logits"]
        )



    # Gradient

    grads = torch.autograd.grad(

        score,

        fused_features,

        retain_graph=False

    )[0]



    # Grad-CAM

    weights = grads.mean(
        dim=-1
    )



    cam = (
        weights *
        fused_features.mean(dim=-1)
    )



    cam = cam.squeeze(0)



    # keep visual tokens

    cam = cam[:196]



    cam = cam.reshape(
        14,
        14
    )



    cam = F.relu(
        cam
    )



    cam = (
        cam -
        cam.min()
    ) / (
        cam.max()
        -
        cam.min()
        +
        1e-8
    )



    # Upsample

    cam = F.interpolate(

        cam.unsqueeze(0)
           .unsqueeze(0),

        size=(224,224),

        mode="bilinear",

        align_corners=False

    )



    heatmap = (
        cam.squeeze()
        .detach()
        .cpu()
        .numpy()
    )



    return heatmap





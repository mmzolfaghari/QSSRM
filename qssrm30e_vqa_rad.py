# ----------------------------------------------------------
# Dataset Class
# ----------------------------------------------------------

class MedicalVQADataset(Dataset):


    def __init__(
        self,
        hf_dataset,
        answer_to_label,
        answer_type_to_label,
        image_transform=None
    ):

        self.dataset = hf_dataset

        self.answer_to_label = answer_to_label

        self.answer_type_to_label = answer_type_to_label

        self.image_transform = image_transform



        self.valid_indices = []

        self.tokens = []

        self.answer_types = []

        self.answer_type_labels = []



        # --------------------------------------------------
        # Filter samples + Cache tokens
        # --------------------------------------------------

        for idx, sample in enumerate(self.dataset):


            answer = (
                str(sample["answer"])
                .lower()
                .strip()
            )


            # Keep only answers in vocabulary

            if answer not in self.answer_to_label:

                continue



            self.valid_indices.append(idx)



            # ------------------------------
            # Question Tokenization
            # ------------------------------

            encoding = tokenizer(

                sample["question"],

                padding="max_length",

                truncation=True,

                max_length=MAX_LENGTH,

                return_tensors="pt"

            )



            self.tokens.append({

                "input_ids":
                    encoding["input_ids"]
                    .squeeze(0),


                "attention_mask":
                    encoding["attention_mask"]
                    .squeeze(0)

            })



            # ------------------------------
            # Ground Truth Answer Type
            # ------------------------------

            answer_type = sample["answer_type"]


            self.answer_types.append(
                answer_type
            )


            self.answer_type_labels.append(

                self.answer_type_to_label[
                    answer_type
                ]

            )




    def __len__(self):

        return len(
            self.valid_indices
        )




    def __getitem__(self, idx):


        real_idx = self.valid_indices[idx]


        sample = self.dataset[real_idx]



        # ------------------------------
        # Image
        # ------------------------------

        image = sample["image"].convert(
            "RGB"
        )


        if self.image_transform:

            image = self.image_transform(
                image
            )



        # ------------------------------
        # Answer
        # ------------------------------

        answer = (
            str(sample["answer"])
            .lower()
            .strip()
        )



        # ------------------------------
        # Return Dictionary
        # ------------------------------

        return {


            "image":

                image,



            "input_ids":

                self.tokens[idx]["input_ids"],



            "attention_mask":

                self.tokens[idx]["attention_mask"],



            "answer_label":

                torch.tensor(

                    self.answer_to_label[answer],

                    dtype=torch.long

                ),



            "answer_type_label":

                torch.tensor(

                    self.answer_type_labels[idx],

                    dtype=torch.long

                ),



            "answer_type":

                self.answer_types[idx],



            "question":

                sample["question"],



            "answer":

                answer

        }





import torch
import torch.nn as nn



class BidirectionalInteraction(nn.Module):

    """
    Inputs
    ------
    SS : [B,N,256]
    PP : [B,N,256]
    SP : [B,N,256]
    PS : [B,N,256]


    Outputs
    -------
    semantic : [B,N,256]
    spatial  : [B,N,256]
    """

    def __init__(
        self,
        feature_dim=256,
        dropout=0.2
    ):

        super().__init__()



        # --------------------------------------------------
        # Semantic Fusion
        # --------------------------------------------------

        self.semantic_fusion = nn.Sequential(

            nn.Linear(
                feature_dim * 2,
                feature_dim
            ),

            nn.GELU(),

            nn.LayerNorm(
                feature_dim
            ),

            nn.Dropout(dropout)

        )



        # --------------------------------------------------
        # Spatial Fusion
        # --------------------------------------------------

        self.spatial_fusion = nn.Sequential(

            nn.Linear(
                feature_dim * 2,
                feature_dim
            ),

            nn.GELU(),

            nn.LayerNorm(
                feature_dim
            ),

            nn.Dropout(dropout)

        )



        # --------------------------------------------------
        # Gates
        # --------------------------------------------------

        self.semantic_gate = nn.Sequential(

            nn.Linear(
                feature_dim * 2,
                feature_dim
            ),

            nn.Sigmoid()

        )


        self.spatial_gate = nn.Sequential(

            nn.Linear(
                feature_dim * 2,
                feature_dim
            ),

            nn.Sigmoid()

        )



        # --------------------------------------------------
        # Gate Initialization
        # More stable for small medical VQA dataset
        # --------------------------------------------------

        nn.init.constant_(
            self.semantic_gate[0].bias,
            -1.0
        )


        nn.init.constant_(
            self.spatial_gate[0].bias,
            -1.0
        )



        # --------------------------------------------------
        # Output Norm
        # --------------------------------------------------

        self.semantic_norm = nn.LayerNorm(
            feature_dim
        )


        self.spatial_norm = nn.LayerNorm(
            feature_dim
        )



    def forward(
        self,
        SS,
        PP,
        SP,
        PS
    ):



        # ==================================================
        # Semantic Interaction
        # ==================================================

        semantic_input = torch.cat(
            [
                SS,
                SP
            ],
            dim=-1
        )



        semantic_update = self.semantic_fusion(
            semantic_input
        )


        semantic_gate = self.semantic_gate(
            semantic_input
        )



        semantic = (

            semantic_gate * semantic_update

            +

            (1 - semantic_gate) *
            (
                0.5 * SS +
                0.5 * SP
            )

        )


        semantic = self.semantic_norm(
            semantic
        )



        # ==================================================
        # Spatial Interaction
        # ==================================================

        spatial_input = torch.cat(
            [
                PP,
                PS
            ],
            dim=-1
        )



        spatial_update = self.spatial_fusion(
            spatial_input
        )


        spatial_gate = self.spatial_gate(
            spatial_input
        )



        spatial = (

            spatial_gate * spatial_update

            +

            (1 - spatial_gate) *
            (
                0.5 * PP +
                0.5 * PS
            )

        )


        spatial = self.spatial_norm(
            spatial
        )



        return (
            semantic,
            spatial
        )


def question_token_importance(sample):


    captured_tokens = None



    # ------------------------------------------------------
    # Hook question_tokens from TextEncoder
    # ------------------------------------------------------

    def hook_fn(module, inputs, output):

        nonlocal captured_tokens

        # TextEncoder output:
        # (global_question, question_tokens)

        captured_tokens = output[1]

        captured_tokens.retain_grad()



    hook = (
        qssrm_model.text_encoder
        .register_forward_hook(hook_fn)
    )



    # ------------------------------------------------------
    # Prepare inputs
    # ------------------------------------------------------

    image = (
        sample["image"]
        .unsqueeze(0)
        .to(DEVICE)
    )


    encoded = tokenizer(

        sample["question"],

        return_tensors="pt",

        padding="max_length",

        truncation=True,

        max_length=MAX_LENGTH

    )


    input_ids = encoded["input_ids"].to(
        DEVICE
    )


    attention_mask = encoded["attention_mask"].to(
        DEVICE
    )



    # ------------------------------------------------------
    # Forward
    # ------------------------------------------------------

    with torch.enable_grad():


        outputs = qssrm_model(

            image,

            input_ids,

            attention_mask

        )



        type_pred = torch.argmax(

            outputs["question_type_logits"],

            dim=-1

        )



        if type_pred.item()==TYPE_YES_NO:


            score = torch.max(

                outputs["yes_no_logits"]

            )


        else:


            score = torch.max(

                outputs["open_logits"]

            )



        qssrm_model.zero_grad()



        score.backward()



    hook.remove()



    # ------------------------------------------------------
    # Extract token gradients
    # ------------------------------------------------------

    if (
        captured_tokens is None
        or
        captured_tokens.grad is None
    ):

        raise RuntimeError(
            "Question token gradients unavailable"
        )



    tokens = captured_tokens



    grads = tokens.grad



    print(
        "Token Feature Shape:",
        tokens.shape
    )



    # ------------------------------------------------------
    # Importance = Gradient x Feature
    # ------------------------------------------------------

    importance = (

        grads *
        tokens

    ).sum(
        dim=-1
    )



    importance = importance.abs()



    importance = importance.squeeze(0)



    mask = (
        attention_mask
        .squeeze(0)
        .bool()
    )



    importance = importance[mask]



    token_ids = (
        input_ids
        .squeeze(0)[mask]
    )



    words = tokenizer.convert_ids_to_tokens(

        token_ids.cpu().numpy()

    )



    # ------------------------------------------------------
    # Remove special tokens
    # ------------------------------------------------------

    clean_words = []

    clean_scores = []



    for w,s in zip(words, importance):


        if w not in [
            "[CLS]",
            "[SEP]",
            "[PAD]"
        ]:


            clean_words.append(w)

            clean_scores.append(
                s.item()
            )



    # ------------------------------------------------------
    # Normalize
    # ------------------------------------------------------

    scores = np.array(
        clean_scores
    )


    scores = (

        scores -
        scores.min()

    ) / (

        scores.max()
        -
        scores.min()
        +
        1e-8

    )



    return (
        clean_words,
        scores
    )





import torch
import torch.nn as nn



# ----------------------------------------------------------
# Question Type Count
# ----------------------------------------------------------

NUM_QUESTION_TYPES = 2



class PredictionHead(nn.Module):


    def __init__(
        self,
        input_dim=256,
        hidden_dim=256,
        num_open_classes=NUM_OPEN_CLASSES,
        num_question_types=NUM_QUESTION_TYPES,
        dropout=0.2
    ):

        super().__init__()



        # --------------------------------------------------
        # Pooling Attention
        # --------------------------------------------------

        self.attention = nn.Sequential(

            nn.Linear(
                input_dim,
                hidden_dim
            ),

            nn.Tanh(),

            nn.Dropout(dropout),

            nn.Linear(
                hidden_dim,
                1
            )

        )



        # --------------------------------------------------
        # Shared Feature Layer
        # --------------------------------------------------

        self.shared = nn.Sequential(

            nn.Linear(
                input_dim,
                hidden_dim
            ),

            nn.GELU(),

            nn.LayerNorm(
                hidden_dim
            ),

            nn.Dropout(dropout)

        )



        # --------------------------------------------------
        # Stage 1: Question Type
        # --------------------------------------------------

        self.question_type_head = nn.Linear(

            hidden_dim,

            num_question_types

        )



        # --------------------------------------------------
        # Stage 2A: Yes/No
        # --------------------------------------------------

        self.yes_no_head = nn.Linear(

            hidden_dim,

            2

        )



        # --------------------------------------------------
        # Stage 2B: Open-ended
        # --------------------------------------------------

        self.open_head = nn.Linear(

            hidden_dim,

            num_open_classes

        )



    def forward(
        self,
        fused_features
    ):

        # fused_features:
        # [B,N,256]


        # --------------------------------------------------
        # Attention Pooling
        # --------------------------------------------------

        attn_logits = self.attention(
            fused_features
        )
        # [B,N,1]


        attention = torch.softmax(
            attn_logits,
            dim=1
        )


        pooled_feature = (
            attention *
            fused_features
        ).sum(
            dim=1
        )
        # [B,256]



        # --------------------------------------------------
        # Shared Representation
        # --------------------------------------------------

        hidden = self.shared(
            pooled_feature
        )



        # --------------------------------------------------
        # Predictions
        # --------------------------------------------------

        question_type_logits = self.question_type_head(
            hidden
        )


        yes_no_logits = self.yes_no_head(
            hidden
        )


        open_logits = self.open_head(
            hidden
        )



        return {

            "question_type_logits":
                question_type_logits,


            "yes_no_logits":
                yes_no_logits,


            "open_logits":
                open_logits,


            "pooled_feature":
                pooled_feature,


            "attention":
                attention

        }






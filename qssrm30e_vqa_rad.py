import torch
import torch.nn as nn



class ReasoningController(nn.Module):

    def __init__(
        self,
        visual_dim=512,
        question_dim=512,
        hidden_dim=256,
        dropout=0.2,
        temperature=1.5
    ):

        super().__init__()


        self.temperature = temperature



        # Input normalization

        self.visual_norm = nn.LayerNorm(
            visual_dim
        )


        self.question_norm = nn.LayerNorm(
            question_dim
        )



        # Controller

        self.controller = nn.Sequential(

            nn.Linear(
                visual_dim + question_dim,
                hidden_dim
            ),

            nn.LayerNorm(
                hidden_dim
            ),

            nn.GELU(),

            nn.Dropout(dropout),



            nn.Linear(
                hidden_dim,
                128
            ),

            nn.GELU(),

            nn.Dropout(dropout)

        )



        # Routing head

        self.routing_head = nn.Linear(
            128,
            4
        )


        # Stable initialization

        nn.init.zeros_(
            self.routing_head.bias
        )



    def forward(
        self,
        global_visual,
        global_question
    ):


        global_visual = self.visual_norm(
            global_visual
        )


        global_question = self.question_norm(
            global_question
        )



        joint = torch.cat(
            [
                global_visual,
                global_question
            ],
            dim=-1
        )



        hidden = self.controller(
            joint
        )


        logits = self.routing_head(
            hidden
        )



        weights = torch.softmax(
            logits / self.temperature,
            dim=-1
        )


        return weights






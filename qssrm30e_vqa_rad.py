def convert_answer_labels_to_two_stage(
    labels
):

    """
    Convert 220-class labels into:

    Stage 1:
        0 -> yes/no
        1 -> open-ended

    Stage 2:
        yes/no -> 0/1
        open -> 0..217

    """



    device = labels.device



    question_type_labels = torch.zeros_like(
        labels
    )



    answer_stage_labels = torch.zeros_like(
        labels
    )



    # ----------------------------
    # Yes / No
    # ----------------------------

    for old_label, new_label in YES_NO_LABEL_MAPPING.items():

        mask = labels == old_label


        question_type_labels[mask] = TYPE_YES_NO


        answer_stage_labels[mask] = new_label



    # ----------------------------
    # Open-ended
    # ----------------------------

    for old_label, new_label in OPEN_LABEL_MAPPING.items():

        mask = labels == old_label


        question_type_labels[mask] = TYPE_OPEN


        answer_stage_labels[mask] = new_label



    return (

        question_type_labels.to(device),

        answer_stage_labels.to(device)

    )





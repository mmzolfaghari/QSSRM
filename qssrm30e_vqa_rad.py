import torch
import torch.nn as nn


class AdaptiveFusion(nn.Module):

    def __init__(
        self,
        feature_dim=256,
        dropout=0.3
    ):

        super().__init__()


        self.refinement = nn.Sequential(

            nn.Linear(
                feature_dim,
                feature_dim
            ),

            nn.GELU(),

            nn.Dropout(dropout),

            nn.Linear(
                feature_dim,
                feature_dim
            )

        )


        self.residual_gate = nn.Sequential(

            nn.Linear(
                feature_dim,
                feature_dim
            ),

            nn.Sigmoid()

        )


        self.norm = nn.LayerNorm(
            feature_dim
        )



    def forward(
        self,
        SS,
        PP,
        SP,
        PS,
        weights
    ):


        # --------------------------------------------------
        # Dimension Safety
        # --------------------------------------------------

        assert SS.shape == PP.shape == SP.shape == PS.shape, \
            f"Reasoning pathway mismatch: {SS.shape}, {PP.shape}, {SP.shape}, {PS.shape}"


        assert weights.ndim == 2 and weights.shape[1] == 4, \
            f"Routing weights must be [B,4], got {weights.shape}"



        # --------------------------------------------------
        # Routing weights
        # --------------------------------------------------

        routing = weights.unsqueeze(-1).unsqueeze(-1)
        # [B,4,1,1]


        paths = torch.stack(
            [
                SS,
                PP,
                SP,
                PS
            ],
            dim=1
        )
        # [B,4,N,256]


        fused = (
            routing * paths
        ).sum(
            dim=1
        )
        # [B,N,256]



        # --------------------------------------------------
        # Residual Cognitive Refinement
        # --------------------------------------------------

        update = self.refinement(
            fused
        )


        gate = self.residual_gate(
            fused
        )


        fused = fused + gate * update



        fused = self.norm(
            fused
        )


        return fused


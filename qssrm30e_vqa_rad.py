import torch
import torch.nn as nn



class QSSRM(nn.Module):

    def __init__(
        self,
        visual_token_dim=512,
        question_token_dim=512,
        visual_global_dim=512,
        question_global_dim=512
    ):

        super().__init__()



        # --------------------------------------------------
        # Encoders
        # --------------------------------------------------

        self.vision_encoder = vision_encoder

        self.text_encoder = text_encoder



        # --------------------------------------------------
        # QSSD Decomposition
        # --------------------------------------------------

        self.decomposition = SemanticSpatialDecomposition(

            visual_input_dim=visual_token_dim,

            question_input_dim=question_token_dim,

            semantic_dim=256,

            spatial_dim=256,

            dropout=0.3

        )



        # --------------------------------------------------
        # Shared Cross Attention
        # --------------------------------------------------

        self.cross_attention = SharedCrossAttention(

            embed_dim=256,

            num_heads=8,

            dropout=0.2

        )



        # --------------------------------------------------
        # Bidirectional Interaction
        # --------------------------------------------------

        self.interaction = BidirectionalInteraction(

            feature_dim=256,

            dropout=0.2

        )



        # --------------------------------------------------
        # Reasoning Controller
        # --------------------------------------------------

        self.controller = ReasoningController(

            visual_dim=visual_global_dim,

            question_dim=question_global_dim,

            hidden_dim=256,

            dropout=0.2,

            temperature=1.5

        )



        # --------------------------------------------------
        # Adaptive Fusion
        # --------------------------------------------------

        self.fusion = AdaptiveFusion(

            feature_dim=256,

            dropout=0.2

        )



        # --------------------------------------------------
        # TWO-STAGE Prediction Head
        # --------------------------------------------------

        self.classifier = PredictionHead(

            input_dim=256,

            hidden_dim=256,

            num_open_classes=NUM_OPEN_CLASSES,

            num_question_types=NUM_QUESTION_TYPES,

            dropout=0.2

        )




    def forward(
        self,
        images,
        input_ids,
        attention_mask
    ):



        # ==================================================
        # Encoding
        # ==================================================

        global_visual, visual_tokens = self.vision_encoder(
            images
        )


        global_question, question_tokens = self.text_encoder(
            input_ids,
            attention_mask
        )



        # ==================================================
        # QSSD
        # ==================================================

        Vs, Vp, Qs, Qp = self.decomposition(

            visual_tokens,

            question_tokens

        )



        # ==================================================
        # Cross Attention
        # ==================================================

        SS, PP, SP, PS, attention = self.cross_attention(

            Vs,

            Vp,

            Qs,

            Qp

        )



        # ==================================================
        # Interaction
        # ==================================================

        semantic, spatial = self.interaction(

            SS,

            PP,

            SP,

            PS

        )



        # ==================================================
        # Reasoning Routing
        # ==================================================

        reasoning_weights = self.controller(

            global_visual,

            global_question

        )



        # ==================================================
        # Adaptive Fusion
        # ==================================================

        fused = self.fusion(

            SS,

            PP,

            SP,

            PS,

            reasoning_weights

        )



        # ==================================================
        # Two-Stage Prediction
        # ==================================================

        output = self.classifier(
            fused
        )



        return {


            "question_type_logits":

                output["question_type_logits"],



            "yes_no_logits":

                output["yes_no_logits"],



            "open_logits":

                output["open_logits"],



            "pooled_feature":

                output["pooled_feature"],



            "attention":

                attention,



            "reasoning_weights":

                reasoning_weights,



            "fused_features":

                fused

        }






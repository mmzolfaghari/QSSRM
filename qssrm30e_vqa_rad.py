import torch
import torch.nn as nn


class SharedCrossAttention(nn.Module):

    """
    Shared Cross-Attention Module

    Inputs
    ------
    Vs : [B,Nv,256]
    Vp : [B,Nv,256]
    Qs : [B,Nq,256]
    Qp : [B,Nq,256]


    Outputs
    -------
    SS, PP, SP, PS : reasoning pathways
    attention       : cross attention weights
    """

    def __init__(
        self,
        embed_dim=256,
        num_heads=8,
        dropout=0.2
    ):

        super().__init__()


        self.visual_norm = nn.LayerNorm(
            embed_dim
        )


        self.question_norm = nn.LayerNorm(
            embed_dim
        )


        self.cross_attention = nn.MultiheadAttention(

            embed_dim=embed_dim,

            num_heads=num_heads,

            dropout=dropout,

            batch_first=True

        )


        self.attn_norm = nn.LayerNorm(
            embed_dim
        )



        self.ffn = nn.Sequential(

            nn.Linear(
                embed_dim,
                embed_dim * 2
            ),

            nn.GELU(),

            nn.Dropout(dropout),

            nn.Linear(
                embed_dim * 2,
                embed_dim
            ),

            nn.Dropout(dropout)

        )


        self.ffn_norm = nn.LayerNorm(
            embed_dim
        )



        self.ss_proj = nn.Sequential(

            nn.Linear(
                embed_dim,
                embed_dim
            ),

            nn.GELU(),

            nn.Dropout(dropout)

        )


        self.pp_proj = nn.Sequential(

            nn.Linear(
                embed_dim,
                embed_dim
            ),

            nn.GELU(),

            nn.Dropout(dropout)

        )


        self.sp_proj = nn.Sequential(

            nn.Linear(
                embed_dim,
                embed_dim
            ),

            nn.GELU(),

            nn.Dropout(dropout)

        )


        self.ps_proj = nn.Sequential(

            nn.Linear(
                embed_dim,
                embed_dim
            ),

            nn.GELU(),

            nn.Dropout(dropout)

        )



    def forward(
        self,
        Vs,
        Vp,
        Qs,
        Qp
    ):


        visual = torch.cat(
            [
                Vs,
                Vp
            ],
            dim=1
        )


        question = torch.cat(
            [
                Qs,
                Qp
            ],
            dim=1
        )



        visual = self.visual_norm(
            visual
        )


        question = self.question_norm(
            question
        )



        context, attention = self.cross_attention(

            query=visual,

            key=question,

            value=question

        )



        context = self.attn_norm(
            context + visual
        )



        context = self.ffn_norm(
            context + self.ffn(context)
        )



        Nv = Vs.shape[1]


        context_sem = context[:, :Nv]

        context_spa = context[:, Nv:Nv*2]



        SS = self.ss_proj(
            context_sem
        )


        PP = self.pp_proj(
            context_spa
        )


        SP = self.sp_proj(
            context_sem
        )


        PS = self.ps_proj(
            context_spa
        )



        return (
            SS,
            PP,
            SP,
            PS,
            attention
        )


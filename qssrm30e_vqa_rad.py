import torch
import torch.nn as nn



class SemanticSpatialDecomposition(nn.Module):


    """
    QSSRM Semantic-Spatial Decomposition


    Visual:
        Vs : Visual Semantic
        Vp : Visual Spatial


    Question:
        Qs : Question Semantic
        Qp : Question Spatial

    """



    def __init__(

        self,

        visual_input_dim=512,

        question_input_dim=512,

        semantic_dim=256,

        spatial_dim=256,

        dropout=0.2

    ):


        super().__init__()



        # -------------------------------
        # Normalization
        # -------------------------------

        self.visual_norm = nn.LayerNorm(
            visual_input_dim
        )


        self.question_norm = nn.LayerNorm(
            question_input_dim
        )



        # -------------------------------
        # Visual Projection
        # -------------------------------

        self.visual_shared = nn.Sequential(

            nn.Linear(
                visual_input_dim,
                semantic_dim
            ),

            nn.GELU(),

            nn.LayerNorm(
                semantic_dim
            ),

            nn.Dropout(dropout)

        )



        # -------------------------------
        # Question Projection
        # -------------------------------

        self.question_shared = nn.Sequential(

            nn.Linear(
                question_input_dim,
                semantic_dim
            ),

            nn.GELU(),

            nn.LayerNorm(
                semantic_dim
            ),

            nn.Dropout(dropout)

        )



        # -------------------------------
        # Separate semantic heads
        # -------------------------------

        self.visual_semantic = nn.Sequential(

            nn.Linear(
                semantic_dim,
                semantic_dim
            ),

            nn.GELU(),

            nn.LayerNorm(
                semantic_dim
            )

        )



        self.question_semantic = nn.Sequential(

            nn.Linear(
                semantic_dim,
                semantic_dim
            ),

            nn.GELU(),

            nn.LayerNorm(
                semantic_dim
            )

        )



        # -------------------------------
        # Spatial heads
        # -------------------------------

        self.visual_spatial = nn.Sequential(

            nn.Linear(
                semantic_dim,
                spatial_dim
            ),

            nn.GELU(),

            nn.LayerNorm(
                spatial_dim
            )

        )



        self.question_spatial = nn.Sequential(

            nn.Linear(
                semantic_dim,
                spatial_dim
            ),

            nn.GELU(),

            nn.LayerNorm(
                spatial_dim
            )

        )





    def forward(

        self,

        visual_tokens,

        question_tokens

    ):



        # visual_tokens:
        # [B,N,512]

        # question_tokens:
        # [B,L,512]



        visual_tokens = self.visual_norm(
            visual_tokens
        )


        question_tokens = self.question_norm(
            question_tokens
        )



        visual_base = self.visual_shared(
            visual_tokens
        )


        question_base = self.question_shared(
            question_tokens
        )



        Vs = self.visual_semantic(
            visual_base
        )


        Vp = self.visual_spatial(
            visual_base
        )



        Qs = self.question_semantic(
            question_base
        )


        Qp = self.question_spatial(
            question_base
        )



        return (

            Vs,

            Vp,

            Qs,

            Qp

        )





